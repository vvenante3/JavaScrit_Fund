var agora = new Date()
var diaSemana = agora.getDay()

switch(diaSemana){
    case 0: 
        console.log(`Hoje é Domingo, é.. tá bão..`)
    break
    case 1:
        console.log(`Hoje é Segunda-Feira, aff`)
    break
    case 2:
        console.log(`Hoje é Terça-Feira, melhor do que nada!`)
    break
    case 3:
        console.log(`Hoje é Quarta-Feira, ok`)
    break
    case 4:
        console.log(`Hoje é Quinta-Feira, tá quase!`)
    break
    case 5:
        console.log(`Hoje é Sexta-Feira Ihaaaaa!`)
    break
    case 6:
        console.log(`Hoje é Sábado, Ueeepaaa!!`)

}